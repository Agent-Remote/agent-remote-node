// SessionAttachmentTransferCapability describes the installed exact-session
// attachment gateway. It is advertised only when the gateway probe succeeds.
type SessionAttachmentTransferCapability struct {
	Supported       bool  `json:"supported"`
	ProtocolVersion int   `json:"protocol_version"`
	MaxBytes        int64 `json:"max_bytes,omitempty"`
	MaxEntries      int   `json:"max_entries,omitempty"`
}

// VerifyExactAttachmentRequest asks the Server for a single-purpose transfer
// lease. The lease ID is generated by the Node and is never client supplied.
type VerifyExactAttachmentRequest struct {
	Version   int    `json:"version"`
	NodeID    string `json:"node_id"`
	SessionID string `json:"session_id"`
	DeviceID  string `json:"device_id"`
	SSHKeyID  string `json:"ssh_key_id"`
	LeaseID   string `json:"lease_id"`
}

// Validate rejects incomplete or noncanonical transfer identities.
func (r VerifyExactAttachmentRequest) Validate() error {
	if r.Version != 1 {
		return errors.New("unsupported exact attachment protocol")
	}
	for _, value := range []string{r.NodeID, r.SessionID, r.DeviceID, r.SSHKeyID, r.LeaseID} {
		if !canonicalAttachUUID(value) {
			return errors.New("exact attachment requires canonical nonzero UUIDs")
		}
	}
	return nil
}

// VerifyExactAttachmentData is an opaque, bounded lease returned by Server.
// RuntimeScope is an opaque token; it is never interpreted as a filesystem path.
type VerifyExactAttachmentData struct {
	Version           int     `json:"version"`
	Operation         string  `json:"operation"`
	NodeID            string  `json:"node_id"`
	SessionID         string  `json:"session_id"`
	DeviceID          string  `json:"device_id"`
	SSHKeyID          string  `json:"ssh_key_id"`
	LeaseID           string  `json:"lease_id"`
	RuntimeBackend    string  `json:"runtime_backend"`
	RuntimeResourceID *string `json:"runtime_resource_id"`
	RuntimeScope      string  `json:"runtime_scope"`
	ExpiresAt         string  `json:"expires_at"`
	MaxBytes          int64   `json:"max_bytes"`
	MaxEntries        int     `json:"max_entries"`
}

// Validate verifies all echoes and lease limits before local filesystem use.
func (d VerifyExactAttachmentData) Validate(request VerifyExactAttachmentRequest) error {
	if d.Version != 1 || d.Operation != "transfer_lease" || d.NodeID != request.NodeID || d.SessionID != request.SessionID || d.DeviceID != request.DeviceID || d.SSHKeyID != request.SSHKeyID || d.LeaseID != request.LeaseID {
		return errors.New("exact attachment authorization identity mismatch")
	}
	if d.RuntimeBackend != "native" && d.RuntimeBackend != "docker_sandbox" {
		return errors.New("exact attachment runtime backend is unsupported")
	}
	if (d.RuntimeResourceID != nil && !safeAttachRuntimeName(*d.RuntimeResourceID)) || d.RuntimeScope == "" || len(d.RuntimeScope) > 4096 || d.ExpiresAt == "" || d.MaxBytes <= 0 || d.MaxBytes > 256*1024*1024 || d.MaxEntries <= 0 || d.MaxEntries > 32 {
		return errors.New("exact attachment authorization limits are invalid")
	}
	if parsed, err := time.Parse(time.RFC3339Nano, d.ExpiresAt); err != nil || !parsed.After(time.Now().UTC()) {
		return errors.New("exact attachment lease is expired")
	}
	return nil
}

// VerifyExactAttachmentResponse wraps a strict transfer lease response.
type VerifyExactAttachmentResponse struct {
	Data      VerifyExactAttachmentData `json:"data"`
	RequestID string                    `json:"request_id"`
}

// UnmarshalJSON rejects unknown, missing, duplicate, or aliased envelope fields.
func (r *VerifyExactAttachmentResponse) UnmarshalJSON(data []byte) error {
	if err := rejectDuplicateJSONKeys(data); err != nil {
		return err
	}
	var fields map[string]json.RawMessage
	if err := json.Unmarshal(data, &fields); err != nil {
		return err
	}
	if len(fields) != 2 || fields["data"] == nil || fields["request_id"] == nil {
		return errors.New("invalid exact attachment envelope")
	}
	for name := range fields {
		if name != "data" && name != "request_id" {
			return errors.New("invalid exact attachment envelope")
		}
	}
	type plain VerifyExactAttachmentResponse
	return json.Unmarshal(data, (*plain)(r))
}

// UnmarshalJSON applies strict field validation to a transfer lease.
func (d *VerifyExactAttachmentData) UnmarshalJSON(data []byte) error {
	if err := rejectDuplicateJSONKeys(data); err != nil {
		return err
	}
	var fields map[string]json.RawMessage
	if err := json.Unmarshal(data, &fields); err != nil {
		return err
	}
	want := []string{"version", "operation", "node_id", "session_id", "device_id", "ssh_key_id", "lease_id", "runtime_backend", "runtime_resource_id", "runtime_scope", "expires_at", "max_bytes", "max_entries"}
	if len(fields) != len(want) {
		return errors.New("invalid exact attachment lease fields")
	}
	for _, name := range want {
		value, ok := fields[name]
		if !ok || bytes.Equal(bytes.TrimSpace(value), []byte("null")) {
			return errors.New("missing exact attachment lease field")
		}
	}
	type plain VerifyExactAttachmentData
	return json.Unmarshal(data, (*plain)(d))
}

// VerifyExactAttachment obtains a transfer lease without redirects or fallback.
func (c Client) VerifyExactAttachment(ctx context.Context, request VerifyExactAttachmentRequest) (VerifyExactAttachmentResponse, error) {
	var response VerifyExactAttachmentResponse
	if err := request.Validate(); err != nil {
		return response, err
	}
	client := *c.httpClient
	client.CheckRedirect = func(*http.Request, []*http.Request) error { return http.ErrUseLastResponse }
	c.httpClient = &client
	if err := c.do(ctx, http.MethodPost, "/api/v1/node-api/attach/exact/attachments/verify", request, &response, true); err != nil {
		return VerifyExactAttachmentResponse{}, errors.New("exact attachment authorization failed")
	}
	if err := response.Data.Validate(request); err != nil {
		return VerifyExactAttachmentResponse{}, err
	}
	return response, nil
}

// CleanupExactAttachmentRequest publishes the durable local cleanup result to
// Server for the same lease. It cannot create or replace a lease.
type CleanupExactAttachmentRequest struct {
	Operation      string `json:"operation,omitempty"`
	Version        int    `json:"version"`
	NodeID         string `json:"node_id"`
	SessionID      string `json:"session_id"`
	DeviceID       string `json:"device_id"`
	SSHKeyID       string `json:"ssh_key_id"`
	LeaseID        string `json:"lease_id"`
	Status         string `json:"status"`
	RemovedBatches int    `json:"removed_batches"`
	ReceiptID      string `json:"receipt_id"`
}

// Validate rejects malformed or out-of-range cleanup publication requests.
func (r CleanupExactAttachmentRequest) Validate() error {
	if r.Version != 1 || (r.Operation != "" && r.Operation != "cleanup_receipt") || !canonicalAttachUUID(r.NodeID) || !canonicalAttachUUID(r.SessionID) || !canonicalAttachUUID(r.DeviceID) || !canonicalAttachUUID(r.SSHKeyID) || !canonicalAttachUUID(r.LeaseID) || !canonicalAttachUUID(r.ReceiptID) || r.RemovedBatches < 0 || r.RemovedBatches > 32 {
		return errors.New("invalid exact attachment cleanup publication")
	}
	switch r.Status {
	case "cleaned", "pending", "unknown", "rejected":
		return nil
	default:
		return errors.New("invalid exact attachment cleanup status")
	}
}

// CleanupExactAttachmentResponse contains Server's immutable cleanup receipt.
type CleanupExactAttachmentResponse struct {
	Data      CleanupExactAttachmentRequest `json:"data"`
	RequestID string                        `json:"request_id"`
}

// UnmarshalJSON rejects unknown cleanup response envelope fields.
func (r *CleanupExactAttachmentResponse) UnmarshalJSON(data []byte) error {
	if err := rejectDuplicateJSONKeys(data); err != nil {
		return err
	}
	var fields map[string]json.RawMessage
	if err := json.Unmarshal(data, &fields); err != nil || len(fields) != 2 || fields["data"] == nil || fields["request_id"] == nil {
		return errors.New("invalid exact attachment cleanup envelope")
	}
	for name := range fields {
		if name != "data" && name != "request_id" {
			return errors.New("invalid exact attachment cleanup envelope")
		}
	}
	type plain CleanupExactAttachmentResponse
	return json.Unmarshal(data, (*plain)(r))
}

// UnmarshalJSON enforces the exact cleanup receipt fields and rejects aliases.
